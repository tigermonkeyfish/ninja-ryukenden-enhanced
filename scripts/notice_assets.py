def generate(directory, version):
    lines = json.loads((directory / 'screen.json').read_text())
    lines = [(row, text.replace('{version}', version.upper()), palette)
             for row, text, palette in lines]
    characters = ' ' + ''.join(sorted(set(''.join(text for _, text, _ in lines)) - {' '}))
    if len(characters) > 32:
        raise ValueError('Notice font exceeds its reserved 1024 bytes')
    font = bytearray()
    for character in characters:
        tile = bytearray(32)
        tile[:16:2] = bytes(GLYPHS[character])
        font.extend(tile)
    bat = [0x100] * (64 * 32)
    used = set()
    for row, text, palette in lines:
        if not 2 <= row <= 26 or len(text) > 28 or palette not in (0, 1) or row in used:
            raise ValueError('Notice text exceeds the visible safe area or overlaps')
        used.add(row)
        column = (32 - len(text)) // 2
        for character in text:
            bat[row * 64 + column] = (palette << 12) | (0x100 + characters.index(character))
            column += 1
    (directory / 'font.bin').write_bytes(font)
    (directory / 'map.bin').write_bytes(struct.pack('<2048H', *bat))
