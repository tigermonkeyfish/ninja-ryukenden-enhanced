#!/usr/bin/env python3
"""NES palette mode data (src/nes-palette), generated at build time.

The NES mode ($2100 bits 3-4 = 01) recolours the game so it reads as NES
Ninja Gaiden, in NES master-palette colours only (the 47 9-bit colours of
the 2C02G composite palette below) and with the PC Engine's full detail.
Its colours are editable data in `src/nes-palette/`, colour values and role
names only:

- `stages/*.json`: one file per PC Engine background colour set (plus the
  3-2 variant of set 6);
- `shared.json`: the HUD colours and Ryu's sprite palette 96;
- `sprites/*.json`: the other sprite palettes (Ryu's effects, bosses,
  enemies, items), grouped by object;
- `animations.json`: the colour lists the game animates (bank 3's
  animation sets, set by $CE8D at the stage load), per list a role of the
  stage file.

Each colour record holds the original PC Engine colour (`pce`, checked
against the original ROM at build time), its role, and the result the role
resolves to (`nes`, the NES code, and `out`, the 9-bit colour written in NES
mode). `override` (a NES code) replaces the role's choice for one record.
`unused` / `keep` records (a palette's transparent colour 0, entries never
shown) take the nearest NES colour, so every colour NES mode loads is an NES
colour.

`python3 scripts/nes_palette.py resolve` recomputes `nes`/`out` after a role
edit; the build resolves the roles itself and fails if a file's stored
results disagree (so the files always show what the ROM gets) or if any
colour is outside the NES set. `python3 scripts/nes_palette.py detail` lists
the palette rows where distinct PC Engine colours share an NES colour.

Resolution ('match' roles, the default), per palette row (16 colours of a
set row, one sprite palette, one animation set): a role names its NES hues
(`ramp`); the candidates are the NES colours of the role's hue columns,
the neighbouring columns and the greys / near-greys, priced by lightness
(CIE L* of the 9-bit colour), the colour's own a*b* only to choose among the
role's hues (CHROMA, CHROMA_EXT beyond them), and the candidate's distance
from the role's hues (the ramp 0, the ramp codes' hue columns PENALTY,
neighbouring columns and near-greys EXT_NEAR plus ROLE_HUE x a*b*; any other
hue EXT_FAR, never chosen; black 0F only for near-black colours). The row's
distinct colours of one role are assigned in their lightness order to
candidates in lightness order, distinct colours to distinct NES colours; two
share one only at MERGE cost, the price of a 30 L* shift, so a row keeps its
detail unless that would re-light it (the build lists such rows). Roles of a
row are resolved largest first and avoid the colours earlier roles took.
This keeps the PC Engine lighting and texture with NES hues. `detail: false` gives the old
per-colour nearest choice inside the hue columns; 'ramp' roles map by
lightness rank onto the ramp, 'fixed' roles take the ramp's first code.

NES colours are converted with the 2C02G composite palette below (NESdev wiki,
"2C02G" generated by pally v0.23.0), not read from any NES ROM.

Outputs (prepare steps, scripts/asset_transforms.py):
- `generate(work, original)`: `nes-tables.inc`, `nes-sets.inc`,
  `nes-sprites-37.inc`, `nes-sprites-45.inc` and `nes-anim.inc` for the
  nes-palette module: per set and per stage (variants) the address of the NES
  copy in the $6000 window, per sprite palette number its copy (bank $37's
  free tail or bank $45), the HUD words, the packed sets and palettes in the
  loader's format ($F2BE: per 8 colours one byte of bit-8 values, most
  significant first, then the 8 low bytes), and the NES copy of bank 3's
  animation table (the original's records with NES lists).
- `enhanced(module, work, original)`: `nes-enhanced.inc` for stage11/stage22,
  the NES versions of their merged palettes (1-1 palette 1, 2-2 palettes
  13/14). Each merged colour is a native backdrop colour; it takes the NES
  colour of the native set entries that supply its pixels (the most pixels).
"""
