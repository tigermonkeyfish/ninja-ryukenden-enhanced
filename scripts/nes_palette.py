ENHANCED = {
    # module: (profile, stage file, {palette label: map rows or None = all})
    'stage11': (0, 1, {'extra_palette_nes': None}),
    'stage22': (3, 4, {'palette13_nes': range(12, 15), 'palette14_nes': range(15, 16)}),
}


def enhanced_palettes(module, original, path=DATA):
    """{label: (merged PC Engine palette, NES palette)} for an Enhanced module."""
    import native_backdrops as NB
    import native_gfx as NG
    profile, setn, labels = ENHANCED[module]
    data = load(path)
    d = next(x for x in data['stages'] if x['set'] == setn and not x.get('variant_of'))
    out_of = {e['index']: int(e['out'], 16) for e in d['entries']}
    backdrop = NG.Backdrop(original, profile)
    words = NB.loop_words(backdrop)
    result = {}
    for label, rows in labels.items():
        ws = words if rows is None else [words[r] for r in rows]
        name = backdrop.name if rows is None else f'{backdrop.name} palette {label}'
        merged = NG.merged_palette(NB.used_colours(backdrop, ws), name)
        sources = collections.defaultdict(collections.Counter)
        for row in ws:
            for w in row:
                pal, px = backdrop.cell(w)
                for line in px:
                    for v in line:
                        if v:
                            sources[backdrop.colour(pal, v)][out_of[pal * 16 + v]] += 1
        nes = []
        for k, c in enumerate(merged):
            if k == 0 or c not in sources:
                nes.append(nes9(nearest(c)))   # transparent / unused entries: the nearest NES colour
            else:
                nes.append(max(sorted(sources[c]), key=lambda o: sources[c][o]))
        result[label] = (merged, nes)
    return result


def enhanced(module, work, original, path=DATA):
    lines = [f'; Generated by scripts/nes_palette.py: NES-mode versions of {module}\'s merged palettes.']
    for label, (merged, nes) in enhanced_palettes(module, original, path).items():
        bad = [c for c in nes if c not in NES_COLOURS]
        if bad:
            raise NesPaletteError(f'{module} {label}: colours outside the NES set {bad}')
        lines += [f'{label}:', ' .dw ' + ','.join(f'${c:03x}' for c in nes)]
    (Path(work) / 'nes-enhanced.inc').write_text('\n'.join(lines) + '\n')


