def dumps(d):
    """JSON with one line per entry (reviewable diffs)."""
    lines = ['{']
    keys = [k for k in d if not k.startswith('_')]
    for k, key in enumerate(keys):
        v = d[key]
        sep = ',' if k < len(keys) - 1 else ''
        if isinstance(v, list) and v and isinstance(v[0], dict) and 'entries' in v[0]:
            lines.append(f'  {json.dumps(key)}: [')
            for i, sp in enumerate(v):
                head = {a: b for a, b in sp.items() if a not in ('entries', 'roles')}
                lines.append('    {')
                lines.append('      ' + ', '.join(f'{json.dumps(a)}: {json.dumps(b)}' for a, b in head.items()) + ',')
                if 'roles' in sp:
                    lines.append('      "roles": {')
                    items = list(sp['roles'].items())
                    lines += [f'        {json.dumps(a)}: {json.dumps(b)}' + (',' if j < len(items) - 1 else '')
                              for j, (a, b) in enumerate(items)]
                    lines.append('      },')
                lines.append('      "entries": [')
                lines += [f'        {json.dumps(e)}' + (',' if j < len(sp['entries']) - 1 else '')
                          for j, e in enumerate(sp['entries'])]
                lines.append('      ]')
                lines.append('    }' + (',' if i < len(v) - 1 else ''))
            lines.append(f'  ]{sep}')
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            lines.append(f'  {json.dumps(key)}: [')
            lines += [f'    {json.dumps(e)}' + (',' if i < len(v) - 1 else '') for i, e in enumerate(v)]
            lines.append(f'  ]{sep}')
        elif isinstance(v, dict):
            lines.append(f'  {json.dumps(key)}: {{')
            items = list(v.items())
            lines += [f'    {json.dumps(a)}: {json.dumps(b)}' + (',' if i < len(items) - 1 else '')
                      for i, (a, b) in enumerate(items)]
            lines.append(f'  }}{sep}')
        else:
            lines.append(f'  {json.dumps(key)}: {json.dumps(v)}{sep}')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def dumps_shared(sh):
    """shared.json: one line per role and per entry."""
    def block(b, pad):
        rows = [f'{pad}"roles": {{']
        rows += [f'{pad}  {json.dumps(k)}: {json.dumps(v)}' + (',' if i < len(b['roles']) - 1 else '')
                 for i, (k, v) in enumerate(b['roles'].items())]
        rows += [f'{pad}}},', f'{pad}"entries": [']
        rows += [f'{pad}  {json.dumps(e)}' + (',' if i < len(b['entries']) - 1 else '')
                 for i, e in enumerate(b['entries'])]
        return rows + [f'{pad}]']
    lines = ['{', f'  "note": {json.dumps(sh["note"])},', '  "hud": {'] + block(sh['hud'], '    ')
    lines += ['  },', '  "sprites": [']
    for i, sp in enumerate(sh['sprites']):
        lines += ['    {', f'      "palette": {sp["palette"]}, "name": {json.dumps(sp["name"])},'] + block(sp, '      ')
        lines.append('    }' + (',' if i < len(sh['sprites']) - 1 else ''))
    return '\n'.join(lines + ['  ]', '}']) + '\n'


def dumps_animations(an):
    lines = ['{', f'  "note": {json.dumps(an["note"])},', '  "sets": [']
    for i, s in enumerate(an['sets']):
        head = {a: b for a, b in s.items() if a not in ('animators', 'roles')}
        lines.append('    {' + ', '.join(f'{json.dumps(a)}: {json.dumps(b)}' for a, b in head.items()) + ',')
        if 'roles' in s:
            lines.append(f'      "roles": {json.dumps(s["roles"])},')
        lines.append('      "animators": [')
        lines += [f'        {json.dumps(a)}' + (',' if j < len(s['animators']) - 1 else '')
                  for j, a in enumerate(s['animators'])]
        lines.append('      ]')
        lines.append('    }' + (',' if i < len(an['sets']) - 1 else ''))
    return '\n'.join(lines + ['  ]', '}']) + '\n'


def _store(entries, roles):
    for e, (code, out) in zip(entries, resolve(entries, roles)):
        e['nes'] = f'{code:02X}'
        e['out'] = f'{out:03X}'


def resolve_files(path=DATA):
    """Rewrite every file's `nes`/`out` from its roles."""
    path = Path(path)
    for p in sorted((path / 'stages').glob('*.json')):
        d = json.loads(p.read_text())
        _store(d['entries'], d['roles'])
        p.write_text(dumps(d))
    for p in sorted((path / 'sprites').glob('*.json')):
        d = json.loads(p.read_text())
        for sp in d['palettes']:
            _store(sp['entries'], {**d.get('roles', {}), **sp.get('roles', {})})
        p.write_text(dumps(d))
    p = path / 'shared.json'
    sh = json.loads(p.read_text())
    _store(sh['hud']['entries'], sh['hud']['roles'])
    for sp in sh['sprites']:
        _store(sp['entries'], sp['roles'])
    p.write_text(dumps_shared(sh))
    p = path / 'animations.json'
    if p.exists():
        data = load(path)
        an = json.loads(p.read_text())
        files = {d['_file']: d for d in data['stages']}
        for s in an['sets']:
            roles = {**files[s['file']]['roles'], **s.get('roles', {})} if s.get('file') else dict(s.get('roles', {}))
            for a in s['animators']:
                res = anim_resolve(s, roles)[a["entry"]]
                a['nes'] = [f'{c:02X}' for c, _ in res]
                a['out'] = [f'{o:03X}' for _, o in res]
        p.write_text(dumps_animations(an))


