class NesPaletteError(ValueError):
    pass


# ------------------------------------------------------------------ colour
def rgb8(c):
    """8-bit RGB of a 9-bit PC Engine colour (GGGRRRBBB)."""
    r, g, b = (c >> 3) & 7, (c >> 6) & 7, c & 7
    return r * 255 // 7, g * 255 // 7, b * 255 // 7


def nes9(code):
    """The 9-bit PC Engine colour nearest a NES palette code."""
    r, g, b = RGB[code & 0x3F]
    return round(g * 7 / 255) << 6 | round(r * 7 / 255) << 3 | round(b * 7 / 255)


def _lin(v):
    v /= 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


_LAB = {}


def lab(rgb):
    if rgb in _LAB:
        return _LAB[rgb]
    r, g, b = (_lin(v) for v in rgb)
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
    fx, fy, fz = f(x), f(y), f(z)
    _LAB[rgb] = (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))
    return _LAB[rgb]


def lightness(c):
    return lab(rgb8(c))[0]


def chroma(c):
    _, a, b = lab(rgb8(c))
    return (a * a + b * b) ** 0.5


def family(code):
    """NES codes in a ramp code's hue column (greys 00 10 20 30); 0D and the
    xE/xF columns have none."""
    h = code & 0x0F
    if h == 0x0F or h >= 0x0D:
        return [0x0F]
    if h == 0:
        return [0x00, 0x10, 0x20, 0x30]
    return [h, 0x10 | h, 0x20 | h, 0x30 | h]


def _canonical():
    """Every NES code with its own 9-bit colour, one code per colour (0F for
    black, 30 for white, 00/10 for the greys)."""
    seen, out = set(), []
    for n in [0x0F, 0x30, 0x00, 0x10] + list(range(64)):
        if (n & 0x0F) >= 0x0D and n not in (0x0F, 0x2D, 0x3D):
            continue
        if nes9(n) not in seen:
            seen.add(nes9(n))
            out.append(n)
    return out


CODES = _canonical()
NES_COLOURS = frozenset(nes9(n) for n in range(64))   # the 47 9-bit NES colours


def nearest(c):
    """The NES code nearest a PC Engine colour (CIE Lab distance)."""
    L, a, b = lab(rgb8(c))
    return min(CODES, key=lambda n: sum((x - y) ** 2 for x, y in zip((L, a, b), lab(rgb8(nes9(n))))))


def _core(role):
    """(ramp codes, the codes of their hue columns and `extra`)."""
    ramp = [int(x, 16) for x in role['ramp']]
    fam = set()
    for n in ramp:
        fam.update([n] if role.get('strict') else family(n))
    fam.update(int(x, 16) for x in role.get('extra', []))
    return ramp, fam


def _hue_penalty(n, ramp, fam):
    """How far a candidate is from the role's NES hues."""
    if n in ramp:
        return 0.0
    if n in fam:
        return PENALTY
    hues = {x & 0x0F for x in ramp if x != 0x0F and (x & 0x0F) < 0x0D}
    h = n & 0x0F
    grey_role = hues <= {0}
    if h == 0 or h == 0x0D or chroma(nes9(n)) < (NEAR_GREY if grey_role else NEAR_GREY_HUED):
        return EXT_NEAR                  # greys and near-greys are near every role
    for x in hues - {0}:
        if 1 <= h <= 12 and min((h - x) % 12, (x - h) % 12) == 1:
            return EXT_NEAR
    return EXT_FAR if not grey_role else EXT_FAR


def _ab2(p, q):
    return (p[1] - q[1]) ** 2 + (p[2] - q[2]) ** 2


def _cost(role, c, n, ramp, fam):
    """Lightness distance, the colour's own hue only to choose among the
    role's hues (its distance to a candidate beyond its distance to the
    nearest role colour), and the candidate's distance from the role's hues
    (its tier and its a*b* distance to the nearest role colour)."""
    pc = lab(rgb8(c))
    L, a, b = pc
    if n == 0x0F and 0x0F not in ramp and not (
            L < 2 or (L < role.get('black_l', BLACK_L) and (a * a + b * b) ** 0.5 < BLACK_CHROMA)):
        return INFEASIBLE        # black only for (near-)black, near-neutral colours
    nc = lab(rgb8(nes9(n)))
    core = [lab(rgb8(nes9(x))) for x in (set(ramp) | fam) - {0x0F}] or [nc]
    # Inside the role's hue columns the colour's hue only picks a column;
    # beyond them it keeps grey colours near-grey and saturated ones saturated.
    weight = role.get('chroma', CHROMA) if n in ramp or n in fam else role.get('chroma_ext', CHROMA_EXT)
    own = max(0.0, _ab2(pc, nc) - min(_ab2(pc, x) for x in core))
    away = min(_ab2(nc, x) for x in core)
    return (L - nc[0]) ** 2 + weight * own + ROLE_HUE * away + _hue_penalty(n, ramp, fam)


def _candidates(role):
    ramp, fam = _core(role)
    exclude = {int(x, 16) for x in role.get('exclude', [])}
    if not role.get('detail', True):
        return ramp, fam, sorted(({0x0F} | fam) - exclude)
    out, seen = [], set()
    for n in ramp + sorted(fam) + CODES:     # the role's own code for a colour first
        if nes9(n) in seen or n in exclude:
            continue
        seen.add(nes9(n))
        out.append(n)
    return ramp, fam, out


def resolve_role(role, colours, taken=frozenset()):
    """{PC Engine colour: NES code} for the colours of one role in one
    palette row. 'match' roles keep detail: distinct colours get distinct NES
    colours in their lightness order (a dynamic programme over the colours
    and the candidates, both in lightness order; two colours share a
    candidate only at MERGE cost). `taken`: 9-bit colours the row's other
    roles already use (sharing one also costs MERGE)."""
    ramp = [int(x, 16) for x in role['ramp']]
    mode = role.get('mode', 'match')
    if mode == 'fixed':
        return {c: ramp[0] for c in colours}
    if mode == 'ramp':
        order = sorted(ramp, key=lambda n: lightness(nes9(n)))
        ls = {c: lightness(c) for c in colours}
        lo, hi = min(ls.values()), max(ls.values())
        out = {}
        for c in colours:
            q = 0 if hi - lo < 1e-6 else (ls[c] - lo) / (hi - lo)
            out[c] = order[min(len(order) - 1, int(q * len(order)))]
        return out
    if mode != 'match':
        raise NesPaletteError(f'unknown role mode {mode}')
    ramp, fam, cands = _candidates(role)
    cols = sorted(set(colours), key=lambda c: (lightness(c), c))
    if not cols:
        return {}
    if not role.get('detail', True):
        return {c: min(cands, key=lambda n: _cost(role, c, n, ramp, fam)) for c in cols}
    cands = sorted(cands, key=lambda n: (lightness(nes9(n)), n))
    k, m = len(cols), len(cands)
    cost = [[_cost(role, c, n, ramp, fam) + (MERGE if nes9(n) in taken else 0) for n in cands] for c in cols]
    inf = float('inf')
    dp = [cost[0][:]]
    back = [[None] * m]
    for i in range(1, k):
        row, brow = [inf] * m, [None] * m
        best, arg = inf, None              # min over j' < j of dp[i-1][j']
        for j in range(m):
            stay = dp[i - 1][j] + MERGE
            if best <= stay:
                row[j], brow[j] = best + cost[i][j], arg
            else:
                row[j], brow[j] = stay + cost[i][j], j
            if dp[i - 1][j] < best:
                best, arg = dp[i - 1][j], j
        dp.append(row)
        back.append(brow)
    j = min(range(m), key=lambda x: (dp[k - 1][x], x))
    out = {}
    for i in range(k - 1, -1, -1):
        out[cols[i]] = cands[j]
        j = back[i][j]
    return out


def _row_key(e):
    return e.get('row')


def resolve(entries, roles):
    """[(nes code, out colour)] for colour records (dicts with pce, role,
    optional override and row) under roles. Roles resolve per row, the
    larger first, each avoiding the colours the row's earlier roles took;
    `unused` / `keep` records take the nearest NES colour."""
    groups = collections.defaultdict(set)
    for e in entries:
        if e['role'] not in ('unused', 'keep'):
            if e['role'] not in roles:
                raise NesPaletteError(f'role {e["role"]} is not defined')
            if not e.get('override'):
                groups[(_row_key(e), e['role'])].add(int(e['pce'], 16))
    rows = collections.defaultdict(list)
    for (row, role), cs in groups.items():
        rows[row].append((role, cs))
    maps = {}
    for row, items in rows.items():
        taken = {nes9(int(e['override'], 16)) for e in entries if _row_key(e) == row and e.get('override')}
        for role, cs in sorted(items, key=lambda x: (-len(x[1]), x[0])):
            r = resolve_role(roles[role], cs, frozenset(taken))
            maps[(row, role)] = r
            taken |= {nes9(n) for n in r.values()}
    out = []
    for e in entries:
        pce = int(e['pce'], 16)
        if e.get('override'):
            code = int(e['override'], 16)
        elif e['role'] in ('unused', 'keep'):
            code = nearest(pce)
        else:
            code = maps[(_row_key(e), e['role'])][pce]
        out.append((code, nes9(code)))
    return out


# ------------------------------------------------------------------ data
def load(path=DATA):
    """{'stages': [...], 'shared': shared.json, 'sprites': [sprite files],
    'animations': animations.json or None}"""
    path = Path(path)
    out = {'stages': [], 'sprites': []}
    for key, folder in (('stages', 'stages'), ('sprites', 'sprites')):
        for p in sorted((path / folder).glob('*.json')):
            d = json.loads(p.read_text())
            d['_file'] = p.name
            out[key].append(d)
    out['shared'] = json.loads((path / 'shared.json').read_text())
    anim = path / 'animations.json'
    out['animations'] = json.loads(anim.read_text()) if anim.exists() else None
    return out


def sprite_records(data):
    """[(palette record, roles, file name)] for every sprite palette with an
    NES copy (shared.json's first, then the sprite files')."""
    out = [(sp, sp['roles'], 'shared.json') for sp in data['shared']['sprites']]
    for d in data['sprites']:
        for sp in d['palettes']:
            out.append((sp, {**d.get('roles', {}), **sp.get('roles', {})}, d['_file']))
    return out


def anim_records(data):
    """[(set record, animator, roles)]: each list resolves as its own row with
    the roles of its stage file (and the set's own `roles`)."""
    if not data.get('animations'):
        return []
    files = {d['_file']: d for d in data['stages']}
    out = []
    for s in data['animations']['sets']:
        roles = {**files[s['file']]['roles'], **s.get('roles', {})} if s.get('file') else dict(s.get('roles', {}))
        for a in s['animators']:
            out.append((s, a, roles))
    return out


def anim_entries(a):
    """An animator's list as colour records."""
    return [{'pce': p, 'role': a['role'], 'row': 0, **({'override': a['override'][i]} if a.get('override') and a['override'][i] else {})}
            for i, p in enumerate(a['pce'])]


def anim_resolve(s, roles):
    """{entry: [(code, out)]}: all lists of one animation set resolve as one
    row, so a colour that travels from entry to entry keeps its NES colour."""
    recs, spans = [], []
    for a in s['animators']:
        e = anim_entries(a)
        spans.append((a['entry'], len(recs), len(recs) + len(e)))
        recs += e
    res = resolve(recs, roles)
    return {entry: res[i:j] for entry, i, j in spans}


def check(data):
    """Structure and stored results: every record resolves to the `nes`/`out`
    it stores, every out colour is an NES colour, sets are covered exactly
    once, sprite palettes at most once with all 16 entries. Returns problems."""
    problems = []
    seen_sets, variants = {}, set()
    for d in data['stages']:
        name = d['_file']
        if set(d) - {'_file', 'stage', 'level_select', 'set', 'variant_of', 'roles', 'notes', 'entries'}:
            problems.append(f'{name}: unexpected keys {sorted(set(d) - {"_file"})}')
        for r, role in d['roles'].items():
            if set(role) - ROLE_KEYS:
                problems.append(f'{name}: role {r} has unexpected keys')
        idx = [e['index'] for e in d['entries']]
        if idx != list(range(len(idx))) or len(idx) % 16:
            problems.append(f'{name}: entries must be indices 0..16n-1 in order')
        for e in d['entries']:
            if set(e) - ENTRY_KEYS:
                problems.append(f'{name}: entry {e["index"]} has unexpected keys')
            if e.get('row') != e['index'] // 16:
                problems.append(f'{name}: entry {e["index"]} names row {e.get("row")}')
        s = d['set']
        if not 0 < s < SETS:
            problems.append(f'{name}: set {s} out of range')
        if d.get('variant_of'):
            for st in d['level_select']:
                if STAGE_SET[st] != s:
                    problems.append(f'{name}: stage {STAGE_NAMES[st]} does not load set {s}')
                if st in variants:
                    problems.append(f'{name}: stage {STAGE_NAMES[st]} has two variants')
                variants.add(st)
        else:
            if s in seen_sets:
                problems.append(f'{name}: set {s} also in {seen_sets[s][0]}')
            seen_sets[s] = (name, d['level_select'])
        problems += _check_results(name, d['entries'], d['roles'])
    for s, (name, stages) in seen_sets.items():
        if sorted(stages) != [st for st, x in enumerate(STAGE_SET) if x == s and st not in variants]:
            problems.append(f'{name}: level_select {stages} is not every stage of set {s} without a variant')
    sh = data['shared']
    problems += _check_results('shared.json hud', sh['hud']['entries'], sh['hud']['roles'])
    if [e['entry'] for e in sh['hud']['entries']] != list(range(1, 8)):
        problems.append('shared.json: the HUD has entries 1-7')
    palettes = set()
    for sp, roles, name in sprite_records(data):
        n = sp['palette']
        if not 0 <= n < SPRITE_PALETTES or n in palettes:
            problems.append(f'{name}: sprite palette {n} out of range or listed twice')
        palettes.add(n)
        if [e['entry'] for e in sp['entries']] != list(range(16)):
            problems.append(f'{name}: sprite palette {n} must list entries 0-15 in order')
        for r, role in roles.items():
            if set(role) - ROLE_KEYS:
                problems.append(f'{name}: role {r} has unexpected keys')
        problems += _check_results(f'{name} sprite {n}', sp['entries'], roles)
    sets_seen = set()
    for s, a, roles in anim_records(data):
        sets_seen.add(s['set'])
        res = anim_resolve(s, roles)[a["entry"]]
        want_nes = [f'{c:02X}' for c, _ in res]
        want_out = [f'{o:03X}' for _, o in res]
        if a.get('nes') != want_nes or a.get('out') != want_out:
            problems.append(f'animations.json: set {s["set"]} entry {a["entry"]} stores {a.get("out")}, '
                            f'its role gives {want_out} (run nes_palette.py resolve)')
        if any(int(o, 16) not in NES_COLOURS for o in a.get('out', [])):
            problems.append(f'animations.json: set {s["set"]} entry {a["entry"]} has a colour outside the NES set')
    if data.get('animations') and sorted(sets_seen) != list(range(ANIM_SETS)):
        problems.append(f'animations.json: sets {sorted(sets_seen)} are not 0-{ANIM_SETS - 1}')
    return problems


def _check_results(name, entries, roles):
    problems = []
    for e, (code, out) in zip(entries, resolve(entries, roles)):
        want_nes = f'{code:02X}'
        if e.get('nes') != want_nes or int(e['out'], 16) != out:
            problems.append(f'{name}: entry {e.get("index", e.get("entry"))} stores nes={e.get("nes")} '
                            f'out={e["out"]}, its role gives {want_nes} {out:03X} (run nes_palette.py resolve)')
        if int(e['out'], 16) not in NES_COLOURS:
            problems.append(f'{name}: entry {e.get("index", e.get("entry"))} out={e["out"]} is not an NES colour')
    return problems


def colours(entries):
    return [int(e['out'], 16) for e in entries]


def originals(entries):
    return [int(e['pce'], 16) for e in entries]


def sprite_palette(sp):
    return colours(sp['entries'])


def pack(cols):
    """The loader's format: per 8 colours a byte of bit-8 values (MSB first), then the 8 low bytes."""
    if len(cols) % 8:
        raise NesPaletteError('a packed palette holds a multiple of 8 colours')
    out = bytearray()
    for g in range(0, len(cols), 8):
        grp = cols[g:g + 8]
        out.append(sum(((c >> 8) & 1) << (7 - k) for k, c in enumerate(grp)))
        out += bytes(c & 0xFF for c in grp)
    return bytes(out)


def unpack(raw, count):
    out = []
    for g in range(count // 8):
        hi = raw[9 * g]
        out += [raw[9 * g + 1 + k] | ((hi >> (7 - k)) & 1) << 8 for k in range(8)]
    return out


def layout(data):
    """ROM-free description of the module's tables:
    {'sets': {set: colours}, 'variants': {stage: (set, colours)},
     'sprites': [(palette, colours)] by palette, 'hud': [7 words],
     'animations': {set: [(entry, colours)]}}"""
    sets, variants = {}, {}
    for d in data['stages']:
        if d.get('variant_of'):
            for st in d['level_select']:
                variants[st] = (d['set'], colours(d['entries']))
        else:
            sets[d['set']] = colours(d['entries'])
    sprites = sorted((sp['palette'], sprite_palette(sp)) for sp, _, _ in sprite_records(data))
    hud = colours(data['shared']['hud']['entries'])
    anims = collections.defaultdict(list)
    for s, a, _ in anim_records(data):
        anims[s['set']].append((a['entry'], [int(x, 16) for x in a['out']]))
    return {'sets': sets, 'variants': variants, 'sprites': sprites, 'hud': hud, 'animations': dict(anims)}


def original_animations(original):
    """The original's animation sets: [[(delay, flag, entry, [colours])]] per set."""
    rd = lambda a: original[ANIM_BANK + a - 0xC000]
    w = lambda a: rd(a) | rd(a + 1) << 8
    out = []
    for s in range(ANIM_SETS):
        p = w(ANIM_TABLE + 2 * s)
        recs = []
        for k in range(rd(p)):
            q = p + 1 + 5 * k
            d, f, e = rd(q), rd(q + 1), rd(q + 2)
            a = rd(q + 3) | rd(q + 4) << 8
            cols = []
            while (w(a) >> 8) != 0xFF:
                cols.append(w(a))
                a += 2
            recs.append((d, f, e, cols, w(a)))
        out.append(recs)
    return out


def verify_original(data, original):
    """The files' original colours must be the original ROM's (headerless image)."""
    problems = []
    for d in data['stages']:
        addr, count = struct.unpack_from('<HH', original, SET_TABLE + 4 * d['set'])
        rom = unpack(original[SET_TABLE + addr - 0x6000:], count)
        if originals(d['entries']) != rom:
            problems.append(f'{d["_file"]}: pce colours differ from set {d["set"]} of the original ROM')
    for sp, _, name in sprite_records(data):
        off = SET_TABLE + SPRITE_BASE - 0x6000 + 18 * sp['palette']
        rom = unpack(original[off:off + 18], 16)
        if originals(sp['entries']) != rom or ('pce' in sp and [int(x, 16) for x in sp['pce']] != rom):
            problems.append(f'{name}: sprite palette {sp["palette"]} differs from the original ROM')
    hud = [original[HUD_TABLE + 2 * k] | original[HUD_TABLE + 2 * k + 1] << 8 for k in range(7)]
    if originals(data['shared']['hud']['entries']) != hud:
        problems.append('shared.json: HUD colours differ from bank 1 $83E5 of the original ROM')
    if data.get('animations'):
        rom = original_animations(original)
        for s in data['animations']['sets']:
            want = [(e, [f'{c:03X}' for c in cols]) for _, _, e, cols, _ in rom[s['set']]]
            have = [(a['entry'], a['pce']) for a in s['animators']]
            if want != have:
                problems.append(f'animations.json: set {s["set"]} differs from the original ROM')
    return problems


def _db(data, per=16):
    return [' .db ' + ','.join(f'${b:02x}' for b in data[i:i + per]) for i in range(0, len(data), per)]


def sprite_range(lay):
    ns = [n for n, _ in lay['sprites']]
    return (min(ns), max(ns)) if ns else (0, -1)


def includes(data, original=None):
    """{file name: text} of the generated include files. The animation table
    (nes-anim.inc) needs the original ROM (the records' delays and flags);
    without it the file is left out."""
    lay = layout(data)
    t = ['; Generated by scripts/nes_palette.py from src/nes-palette/*.json.']
    addr45 = lambda label: f'{label}+${WINDOW:04x}'
    set_label = lambda s: f'nes_set_{s}' if s in lay['sets'] else None
    t.append('nes_set_lo:')
    t.append(' .db ' + ','.join(f'LOW({addr45(set_label(s))})' if set_label(s) else '0' for s in range(SETS)))
    t.append('nes_set_hi:')
    t.append(' .db ' + ','.join(f'HIGH({addr45(set_label(s))})+${BANK45:02x}' if set_label(s) else '0' for s in range(SETS)))
    t.append('nes_variant_set:')
    t.append(' .db ' + ','.join(str(lay['variants'][st][0]) if st in lay['variants'] else '$ff' for st in range(SETS)))
    t.append('nes_variant_lo:')
    t.append(' .db ' + ','.join(f'LOW({addr45(f"nes_variant_{st}")})' if st in lay['variants'] else '0' for st in range(SETS)))
    t.append('nes_variant_hi:')
    t.append(' .db ' + ','.join(f'HIGH({addr45(f"nes_variant_{st}")})+${BANK45:02x}' if st in lay['variants'] else '0' for st in range(SETS)))
    # Sprite palettes: the first that fit go to bank $37's free tail (read
    # in place, MPR3 = $37), the rest to bank $45 after the sets.
    first, last = sprite_range(lay)
    per37 = (REGION_37[1] - REGION_37[0]) // 18
    in37 = {n for n, _ in lay['sprites'][:per37]}
    t.append(f'NES_SPRITE_FIRST = {first}')
    t.append(f'NES_SPRITE_COUNT = {last - first + 1}')
    have = dict(lay['sprites'])
    lo, hi = [], []
    for n in range(first, last + 1):
        if n not in have:
            lo.append('0')
            hi.append('0')
        elif n in in37:
            lo.append(f'LOW(nes_sprite_{n})')
            hi.append(f'HIGH(nes_sprite_{n})')
        else:
            lo.append(f'LOW({addr45(f"nes_sprite_{n}")})')
            hi.append(f'HIGH({addr45(f"nes_sprite_{n}")})+${BANK45:02x}')
    for name, vals in (('lo', lo), ('hi', hi)):
        t.append(f'nes_sprite_{name}:')
        t += [' .db ' + ','.join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    t.append('nes_hud_colours:')
    t.append(' .dw ' + ','.join(f'${c:03x}' for c in lay['hud']))
    for st, (s, cols) in sorted(lay['variants'].items()):
        t.append(f'nes_variant_{st}:   ; {STAGE_NAMES[st]}: set {s}')
        t += _db(pack(cols), 9)
    sets = ['; Generated by scripts/nes_palette.py from src/nes-palette/*.json.']
    for s, cols in sorted(lay['sets'].items()):
        sets.append(f'nes_set_{s}:   ; {len(cols)} colours')
        sets += _db(pack(cols), 9)
    s37 = ['; Generated by scripts/nes_palette.py: NES sprite palettes in bank $37 (read in place).']
    s45 = ['; Generated by scripts/nes_palette.py: NES sprite palettes in bank $45.']
    for n, cols in lay['sprites']:
        dst = s37 if n in in37 else s45
        dst.append(f'nes_sprite_{n}:')
        dst += _db(pack(cols), 9)
    out = {'nes-tables.inc': '\n'.join(t) + '\n', 'nes-sets.inc': '\n'.join(sets) + '\n',
           'nes-sprites-37.inc': '\n'.join(s37) + '\n', 'nes-sprites-45.inc': '\n'.join(s45) + '\n'}
    if original is not None and lay['animations']:
        out['nes-anim.inc'] = anim_include(lay, original)
    return out


def anim_include(lay, original):
    """The NES copy of bank 3's animation table: pointer table, records with
    the original delays, flags and entries, NES lists (same lengths and end
    words, so every tick costs what the original's does)."""
    rom = original_animations(original)
    t = ['; Generated by scripts/nes_palette.py: the NES animation table (bank 3, original layout).',
         'nes_anim:',
         ' .dw ' + ','.join(f'nes_anim_set_{s}' for s in range(ANIM_SETS))]
    for s in range(ANIM_SETS):
        recs = rom[s]
        nes = dict(lay['animations'].get(s, []))
        t.append(f'nes_anim_set_{s}:')
        t.append(f' .db {len(recs)}')
        for k, (d, f, e, cols, end) in enumerate(recs):
            t.append(f' .db {d},{f},{e}')
            t.append(f' .dw nes_anim_list_{s}_{k}')
        for k, (d, f, e, cols, end) in enumerate(recs):
            new = nes.get(e)
            if new is None or len(new) != len(cols):
                raise NesPaletteError(f'animation set {s} entry {e}: no NES list of {len(cols)} colours')
            t.append(f'nes_anim_list_{s}_{k}:')
            t.append(' .dw ' + ','.join(f'${c:03x}' for c in new) + f',${end:04x}')
    return '\n'.join(t) + '\n'


def nes_problems(lay):
    """Every colour in the tables must be one of the 47 NES colours."""
    bad = []
    for s, cols in lay['sets'].items():
        bad += [f'set {s} entry {i}: {c:03X}' for i, c in enumerate(cols) if c not in NES_COLOURS]
    for st, (s, cols) in lay['variants'].items():
        bad += [f'variant {STAGE_NAMES[st]} entry {i}: {c:03X}' for i, c in enumerate(cols) if c not in NES_COLOURS]
    for n, cols in lay['sprites']:
        bad += [f'sprite {n} entry {i}: {c:03X}' for i, c in enumerate(cols) if c not in NES_COLOURS]
    bad += [f'HUD {i}: {c:03X}' for i, c in enumerate(lay['hud']) if c not in NES_COLOURS]
    for s, lists in lay['animations'].items():
        for e, cols in lists:
            bad += [f'animation {s} entry {e}: {c:03X}' for c in cols if c not in NES_COLOURS]
    return bad


def detail_report(data):
    """[(file, row, PC Engine distinct, NES distinct)] for every row whose
    visible colours lose distinctness (BG rows: entries 1-15, row 0 also
    entry 0; sprite palettes: 1-15; animation lists: the whole list)."""
    out = []
    for d in data['stages']:
        res = resolve(d['entries'], d['roles'])
        rows = collections.defaultdict(lambda: (set(), set()))
        for e, (_, o) in zip(d['entries'], res):
            if e['index'] % 16 or e['index'] == 0:
                rows[e['index'] // 16][0].add(int(e['pce'], 16))
                rows[e['index'] // 16][1].add(o)
        out += [(d['_file'], f'row {r}', len(p), len(n)) for r, (p, n) in sorted(rows.items())]
    for sp, roles, name in sprite_records(data):
        res = resolve(sp['entries'], roles)
        p = {int(e['pce'], 16) for e in sp['entries'][1:]}
        n = {o for _, o in res[1:]}
        out.append((name, f'sprite {sp["palette"]}', len(p), len(n)))
    for s, a, roles in anim_records(data):
        res = anim_resolve(s, roles)[a["entry"]]
        out.append(('animations.json', f'set {s["set"]} entry {a["entry"]}', len(set(a['pce'])), len({o for _, o in res})))
    return out


def generate(work, original, path=DATA):
    data = load(path)
    problems = check(data) + verify_original(data, original)
    lay = layout(data)
    problems += nes_problems(lay)
    if problems:
        raise NesPaletteError('NES palette data:\n  ' + '\n  '.join(problems))
    for name, text in includes(data, original).items():
        (Path(work) / name).write_text(text)
    rows = detail_report(data)
    lost = [r for r in rows if r[3] < r[2]]
    if lost:
        per = collections.Counter()
        for f, _, p, n in lost:
            per[f] += p - n
        print(f'NES palette: {len(lost)} of {len(rows)} rows keep fewer distinct colours than the original '
              f'({sum(per.values())} merged; nes_palette.py detail lists them): '
              + ', '.join(f'{f} {k}' for f, k in sorted(per.items())))
    return lay


