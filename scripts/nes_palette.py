#!/usr/bin/env python3
"""NES palette mode data (src/nes-palette), generated at build time.

The NES mode ($2100 bits 3-4 = 01) recolours each stage so it reads as the
corresponding stage of NES Ninja Gaiden. Its colours are editable data in
`src/nes-palette/`: one JSON file per PC Engine palette set (stage files) and
`shared.json` (the HUD colours and Ryu's sprite palette). Each file holds only
colour values and role names:

- `roles`: name -> NES palette codes (`ramp`) and how a PC Engine colour picks
  one of them (below);
- `entries`: every colour of the set: its index, the original PC Engine colour
  (`pce`, checked against the original ROM at build time), its role, and the
  result the role resolves to (`nes`, the NES code, and `out`, the PC Engine
  colour written in NES mode). `override` (a NES code) replaces the role's
  choice for one entry. Roles `keep` and `unused` keep the original colour.

`python3 scripts/nes_palette.py resolve` recomputes `nes`/`out` after a role
edit; the build resolves the roles itself and fails if a file's stored
results disagree (so the files always show what the ROM gets).

Resolution ('match' roles, the default): the candidates are the NES colours of
the hue columns of the role's ramp codes plus black 0F; a PC Engine colour
takes the candidate whose CIE L* (of its 9-bit conversion) is closest to its
own, plus CHROMA x the a*b* distance (picks the hue column inside a multi-hue
role), a candidate outside the ramp itself paying PENALTY. This keeps the PC
Engine lighting with NES hues. 'ramp' roles map by lightness rank onto the
ramp, 'fixed' roles take the ramp's first code, 'strict' roles use the ramp
codes (and 0F) only.

NES colours are converted with the 2C02G composite palette below (NESdev wiki,
"2C02G" generated by pally v0.23.0), not read from any NES ROM.

Outputs (prepare steps, scripts/asset_transforms.py):
- `generate(work, original)`: `nes-tables.inc` and `nes-sets.inc` for the
  nes-palette module: per set and per stage (variants) the address of the NES
  copy in the $6000 window (0 = original), the sprite palettes replaced, the
  HUD words, and the packed sets in the loader's format ($F2BE: per 8 colours
  one byte of bit-8 values, most significant first, then the 8 low bytes).
- `enhanced(module, work, original)`: `nes-enhanced.inc` for stage11/stage22,
  the NES versions of their merged palettes (1-1 palette 1, 2-2 palettes
  13/14). Each merged colour is a native backdrop colour; it takes the NES
  colour of the native set entries that supply its pixels (the most pixels).
"""
import collections
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src/nes-palette'
STAGE_NAMES = ['1-1', '1-2', '2-1', '2-2', '2-3', '3-1', '3-2', '3-3', '4-1', '4-2', '4-3', '4-4',
               '5-1', '5-2', '5-3', '5-4', '6-1', '6-2', '6-3', '6-4A', '6-4B', '6-4C']
# The colour set each Level Select stage ($2E5F) loads with $F211 (measured:
# research/tools/nes-palette/loads.py, all 22 entries and the 11 stored runs).
STAGE_SET = [1, 2, 3, 4, 5, 6, 6, 7, 8, 9, 10, 11, 12, 13, 14, 14, 14, 15, 16, 17, 17, 18]
SETS = 22                     # the set table at bank $37 $6000
SET_TABLE = 0x37 * 0x2000     # headerless ROM offset of bank $37
SPRITE_BASE = 0x7180          # sprite palette n at $37:$7180 + 18n ($F1C0)
HUD_TABLE = 0x2000 + 0x03E5   # bank 1 $83E5: 7 HUD words for entries $F1-$F7
WINDOW = 0x2000               # code runs in MPR2 ($4000), F2BE reads MPR3 ($6000)

PENALTY = 60.0
BLACK_L = 7.0
BLACK_CHROMA = 20.0
CHROMA = 0.15
ENTRY_KEYS = {'index', 'row', 'entry', 'pce', 'role', 'nes', 'out', 'override'}
ROLE_KEYS = {'ramp', 'mode', 'strict', 'chroma', 'black_l', 'extra', 'exclude', 'note'}

NES_2C02G = """
575757,000C8E,0800A6,340096,550061,630015,5A0000,3C0E00,112800,003B00,004200,003A05,002652,000000,000000,000000,
A5A5A5,0041D9,2F1EFF,6704F2,9400B4,AA0057,A31800,803900,4B5B00,137600,008100,007923,006288,000000,000000,000000,
FFFFFF,4A9FFF,797EFF,AF63FF,DD55FF,F757C2,F76A63,DC8810,AEA900,78C400,4AD211,2FCF64,2FBDC4,414141,000000,000000,
FFFFFF,B9DDFF,CAD1FF,DEC6FF,F0C0FF,FCC0EE,FDC6CA,F5D0AA,E4DD95,D0E892,BDEEA2,B2EEC0,B0E8E3,B3B3B3,000000,000000"""
RGB = [tuple(int(v[i:i + 2], 16) for i in (0, 2, 4))
       for v in (x.strip() for x in NES_2C02G.replace('\n', '').split(',')) if v]


class NesPaletteError(ValueError):
    pass


# ------------------------------------------------------------------ colour
def rgb8(c):
    """8-bit RGB of a 9-bit PC Engine colour (GGGRRRBBB)."""
    r, g, b = (c >> 3) & 7, (c >> 6) & 7, c & 7
    return r * 255 // 7, g * 255 // 7, b * 255 // 7


def nes9(code):
    """The 9-bit PC Engine colour nearest a NES palette code."""
    r, g, b = RGB[code & 0x3F]
    return round(g * 7 / 255) << 6 | round(r * 7 / 255) << 3 | round(b * 7 / 255)


def _lin(v):
    v /= 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def lab(rgb):
    r, g, b = (_lin(v) for v in rgb)
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
    fx, fy, fz = f(x), f(y), f(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def lightness(c):
    return lab(rgb8(c))[0]


def family(code):
    """NES codes in a ramp code's hue column (greys 00 10 20 30); 0D and the
    xE/xF columns have none."""
    h = code & 0x0F
    if h == 0x0F or h >= 0x0D:
        return [0x0F]
    if h == 0:
        return [0x00, 0x10, 0x20, 0x30]
    return [h, 0x10 | h, 0x20 | h, 0x30 | h]


def resolve_role(role, colours):
    """{PC Engine colour: NES code} for the colours given one role."""
    ramp = [int(x, 16) for x in role['ramp']]
    mode = role.get('mode', 'match')
    if mode == 'fixed':
        return {c: ramp[0] for c in colours}
    if mode == 'ramp':
        order = sorted(ramp, key=lambda n: lightness(nes9(n)))
        ls = {c: lightness(c) for c in colours}
        lo, hi = min(ls.values()), max(ls.values())
        out = {}
        for c in colours:
            q = 0 if hi - lo < 1e-6 else (ls[c] - lo) / (hi - lo)
            out[c] = order[min(len(order) - 1, int(q * len(order)))]
        return out
    if mode != 'match':
        raise NesPaletteError(f'unknown role mode {mode}')
    cands = {0x0F}
    for n in ramp:
        cands.update([n] if role.get('strict') else family(n))
    extra = [int(x, 16) for x in role.get('extra', [])]
    cands.update(extra)
    cands -= {int(x, 16) for x in role.get('exclude', [])}
    weight = role.get('chroma', CHROMA)
    out = {}
    for c in colours:
        L, a, b = lab(rgb8(c))

        def cost(n):
            if n == 0x0F and 0x0F not in ramp and not (
                    L < 2 or (L < role.get('black_l', BLACK_L) and (a * a + b * b) ** 0.5 < BLACK_CHROMA)):
                return 1e9          # black only for (near-)black, near-neutral colours
            L2, a2, b2 = lab(rgb8(nes9(n)))
            return ((L - L2) ** 2 + weight * ((a - a2) ** 2 + (b - b2) ** 2) +
                    (0 if n in ramp or n in extra else PENALTY))
        out[c] = min(sorted(cands), key=cost)
    return out


def resolve(entries, roles):
    """[(nes code or None, out colour)] for entries (dicts with pce, role,
    optional override) under roles."""
    groups = collections.defaultdict(set)
    for e in entries:
        if e['role'] not in ('unused', 'keep'):
            if e['role'] not in roles:
                raise NesPaletteError(f'role {e["role"]} is not defined')
            groups[e['role']].add(int(e['pce'], 16))
    maps = {r: resolve_role(roles[r], cs) for r, cs in groups.items()}
    out = []
    for e in entries:
        pce = int(e['pce'], 16)
        if e['role'] in ('unused', 'keep'):
            out.append((None, pce))
        else:
            code = int(e['override'], 16) if e.get('override') else maps[e['role']][pce]
            out.append((code, nes9(code)))
    return out


# ------------------------------------------------------------------ data
def load(path=DATA):
    """{'stages': [stage file dicts, sorted by name], 'shared': shared.json}"""
    path = Path(path)
    stages = []
    for p in sorted((path / 'stages').glob('*.json')):
        d = json.loads(p.read_text())
        d['_file'] = p.name
        stages.append(d)
    return {'stages': stages, 'shared': json.loads((path / 'shared.json').read_text())}


def check(data):
    """Structure and stored results: every file's entries resolve to the
    `nes`/`out` it stores; sets are covered exactly once. Returns problems."""
    problems = []
    seen_sets, variants = {}, set()
    for d in data['stages']:
        name = d['_file']
        if set(d) - {'_file', 'stage', 'level_select', 'set', 'variant_of', 'roles', 'notes', 'entries'}:
            problems.append(f'{name}: unexpected keys {sorted(set(d) - {"_file"})}')
        for r, role in d['roles'].items():
            if set(role) - ROLE_KEYS:
                problems.append(f'{name}: role {r} has unexpected keys')
        idx = [e['index'] for e in d['entries']]
        if idx != list(range(len(idx))) or len(idx) % 16:
            problems.append(f'{name}: entries must be indices 0..16n-1 in order')
        for e in d['entries']:
            if set(e) - ENTRY_KEYS:
                problems.append(f'{name}: entry {e["index"]} has unexpected keys')
        s = d['set']
        if not 0 < s < SETS:
            problems.append(f'{name}: set {s} out of range')
        if d.get('variant_of'):
            for st in d['level_select']:
                if STAGE_SET[st] != s:
                    problems.append(f'{name}: stage {STAGE_NAMES[st]} does not load set {s}')
                if st in variants:
                    problems.append(f'{name}: stage {STAGE_NAMES[st]} has two variants')
                variants.add(st)
        else:
            if s in seen_sets:
                problems.append(f'{name}: set {s} also in {seen_sets[s][0]}')
            seen_sets[s] = (name, d['level_select'])
        problems += _check_results(name, d['entries'], d['roles'])
    for s, (name, stages) in seen_sets.items():
        if sorted(stages) != [st for st, x in enumerate(STAGE_SET) if x == s and st not in variants]:
            problems.append(f'{name}: level_select {stages} is not every stage of set {s} without a variant')
    sh = data['shared']
    problems += _check_results('shared.json hud', sh['hud']['entries'], sh['hud']['roles'])
    for sp in sh['sprites']:
        problems += _check_results(f'shared.json sprite {sp["palette"]}', sp['entries'], sp['roles'])
    if [e['entry'] for e in sh['hud']['entries']] != list(range(1, 8)):
        problems.append('shared.json: the HUD has entries 1-7')
    return problems


def _check_results(name, entries, roles):
    problems = []
    for e, (code, out) in zip(entries, resolve(entries, roles)):
        want_nes = None if code is None else f'{code:02X}'
        if e.get('nes') != want_nes or int(e['out'], 16) != out:
            problems.append(f'{name}: entry {e.get("index", e.get("entry"))} stores nes={e.get("nes")} '
                            f'out={e["out"]}, its role gives {want_nes} {out:03X} (run nes_palette.py resolve)')
    return problems


def colours(entries):
    return [int(e['out'], 16) for e in entries]


def originals(entries):
    return [int(e['pce'], 16) for e in entries]


def sprite_palette(sp):
    """16 colours of a sprite palette record: entry 0 and those not listed keep `pce0`."""
    out = [int(x, 16) for x in sp['pce']]
    for e in sp['entries']:
        out[e['entry']] = int(e['out'], 16)
    return out


def pack(cols):
    """The loader's format: per 8 colours a byte of bit-8 values (MSB first), then the 8 low bytes."""
    if len(cols) % 8:
        raise NesPaletteError('a packed palette holds a multiple of 8 colours')
    out = bytearray()
    for g in range(0, len(cols), 8):
        grp = cols[g:g + 8]
        out.append(sum(((c >> 8) & 1) << (7 - k) for k, c in enumerate(grp)))
        out += bytes(c & 0xFF for c in grp)
    return bytes(out)


def unpack(raw, count):
    out = []
    for g in range(count // 8):
        hi = raw[9 * g]
        out += [raw[9 * g + 1 + k] | ((hi >> (7 - k)) & 1) << 8 for k in range(8)]
    return out


def layout(data):
    """ROM-free description of the module's tables:
    {'sets': {set: colours}, 'variants': {stage: (set, colours)},
     'sprites': [(palette, colours)], 'hud': [7 words]}"""
    sets, variants = {}, {}
    for d in data['stages']:
        if d.get('variant_of'):
            for st in d['level_select']:
                variants[st] = (d['set'], colours(d['entries']))
        else:
            sets[d['set']] = colours(d['entries'])
    sprites = [(sp['palette'], sprite_palette(sp)) for sp in data['shared']['sprites']]
    hud = colours(data['shared']['hud']['entries'])
    return {'sets': sets, 'variants': variants, 'sprites': sprites, 'hud': hud}


def verify_original(data, original):
    """The files' original colours must be the original ROM's (headerless image)."""
    import struct
    problems = []
    for d in data['stages']:
        addr, count = struct.unpack_from('<HH', original, SET_TABLE + 4 * d['set'])
        rom = unpack(original[SET_TABLE + addr - 0x6000:], count)
        if originals(d['entries']) != rom:
            problems.append(f'{d["_file"]}: pce colours differ from set {d["set"]} of the original ROM')
    for sp in data['shared']['sprites']:
        off = SET_TABLE + SPRITE_BASE - 0x6000 + 18 * sp['palette']
        rom = unpack(original[off:off + 18], 16)
        if [int(x, 16) for x in sp['pce']] != rom or any(int(e['pce'], 16) != rom[e['entry']] for e in sp['entries']):
            problems.append(f'shared.json: sprite palette {sp["palette"]} differs from the original ROM')
    hud = [original[HUD_TABLE + 2 * k] | original[HUD_TABLE + 2 * k + 1] << 8 for k in range(7)]
    if originals(data['shared']['hud']['entries']) != hud:
        problems.append('shared.json: HUD colours differ from bank 1 $83E5 of the original ROM')
    return problems


def _db(data, per=16):
    return [' .db ' + ','.join(f'${b:02x}' for b in data[i:i + per]) for i in range(0, len(data), per)]


def includes(data):
    """(nes-tables.inc, nes-sets.inc) text."""
    lay = layout(data)
    t = ['; Generated by scripts/nes_palette.py from src/nes-palette/*.json.',
         f'NES_SPRITE_COUNT = {len(lay["sprites"])}']
    addr = lambda label: f'{label}+${WINDOW:04x}'
    set_label = lambda s: f'nes_set_{s}' if s in lay['sets'] else None
    t.append('nes_set_lo:')
    t.append(' .db ' + ','.join(f'LOW({addr(set_label(s))})' if set_label(s) else '0' for s in range(SETS)))
    t.append('nes_set_hi:')
    t.append(' .db ' + ','.join(f'HIGH({addr(set_label(s))})' if set_label(s) else '0' for s in range(SETS)))
    t.append('nes_variant_set:')
    t.append(' .db ' + ','.join(str(lay['variants'][st][0]) if st in lay['variants'] else '$ff' for st in range(SETS)))
    t.append('nes_variant_lo:')
    t.append(' .db ' + ','.join(f'LOW({addr(f"nes_variant_{st}")})' if st in lay['variants'] else '0' for st in range(SETS)))
    t.append('nes_variant_hi:')
    t.append(' .db ' + ','.join(f'HIGH({addr(f"nes_variant_{st}")})' if st in lay['variants'] else '0' for st in range(SETS)))
    for name, field in (('src_lo', lambda n: f'LOW(${SPRITE_BASE + 18 * n:04x})'),
                        ('src_hi', lambda n: f'HIGH(${SPRITE_BASE + 18 * n:04x})'),
                        ('lo', lambda n: f'LOW({addr(f"nes_sprite_{n}")})'),
                        ('hi', lambda n: f'HIGH({addr(f"nes_sprite_{n}")})')):
        t.append(f'nes_sprite_{name}:')
        t.append(' .db ' + ','.join(field(n) for n, _ in lay['sprites']) if lay['sprites'] else ' ; none')
    t.append('nes_hud_colours:')
    t.append(' .dw ' + ','.join(f'${c:03x}' for c in lay['hud']))
    for n, cols in lay['sprites']:
        t.append(f'nes_sprite_{n}:')
        t += _db(pack(cols), 9)
    for st, (s, cols) in sorted(lay['variants'].items()):
        t.append(f'nes_variant_{st}:   ; {STAGE_NAMES[st]}: set {s}')
        t += _db(pack(cols), 9)
    sets = ['; Generated by scripts/nes_palette.py from src/nes-palette/*.json.']
    for s, cols in sorted(lay['sets'].items()):
        sets.append(f'nes_set_{s}:   ; {len(cols)} colours')
        sets += _db(pack(cols), 9)
    return '\n'.join(t) + '\n', '\n'.join(sets) + '\n'


def generate(work, original, path=DATA):
    data = load(path)
    problems = check(data) + verify_original(data, original)
    if problems:
        raise NesPaletteError('NES palette data:\n  ' + '\n  '.join(problems))
    tables, sets = includes(data)
    (Path(work) / 'nes-tables.inc').write_text(tables)
    (Path(work) / 'nes-sets.inc').write_text(sets)
    return layout(data)


# ------------------------------------------------------------------ Enhanced
ENHANCED = {
    # module: (profile, stage file, {palette label: map rows or None = all})
    'stage11': (0, 1, {'extra_palette_nes': None}),
    'stage22': (3, 4, {'palette13_nes': range(12, 15), 'palette14_nes': range(15, 16)}),
}


def enhanced_palettes(module, original, path=DATA):
    """{label: (merged PC Engine palette, NES palette)} for an Enhanced module."""
    import native_backdrops as NB
    import native_gfx as NG
    profile, setn, labels = ENHANCED[module]
    data = load(path)
    d = next(x for x in data['stages'] if x['set'] == setn and not x.get('variant_of'))
    out_of = {e['index']: int(e['out'], 16) for e in d['entries']}
    backdrop = NG.Backdrop(original, profile)
    words = NB.loop_words(backdrop)
    result = {}
    for label, rows in labels.items():
        ws = words if rows is None else [words[r] for r in rows]
        name = backdrop.name if rows is None else f'{backdrop.name} palette {label}'
        merged = NG.merged_palette(NB.used_colours(backdrop, ws), name)
        sources = collections.defaultdict(collections.Counter)
        for row in ws:
            for w in row:
                pal, px = backdrop.cell(w)
                for line in px:
                    for v in line:
                        if v:
                            sources[backdrop.colour(pal, v)][out_of[pal * 16 + v]] += 1
        nes = []
        for k, c in enumerate(merged):
            if k == 0 or c not in sources:
                nes.append(c)               # transparent / unused entries keep their colour
            else:
                nes.append(max(sorted(sources[c]), key=lambda o: sources[c][o]))
        result[label] = (merged, nes)
    return result


def enhanced(module, work, original, path=DATA):
    lines = [f'; Generated by scripts/nes_palette.py: NES-mode versions of {module}\'s merged palettes.']
    for label, (merged, nes) in enhanced_palettes(module, original, path).items():
        lines += [f'{label}:', ' .dw ' + ','.join(f'${c:03x}' for c in nes)]
    (Path(work) / 'nes-enhanced.inc').write_text('\n'.join(lines) + '\n')


# ------------------------------------------------------------------ files
def dumps(d):
    """JSON with one line per entry (reviewable diffs)."""
    lines = ['{']
    keys = [k for k in d if not k.startswith('_')]
    for k, key in enumerate(keys):
        v = d[key]
        sep = ',' if k < len(keys) - 1 else ''
        if isinstance(v, list) and v and isinstance(v[0], dict):
            lines.append(f'  {json.dumps(key)}: [')
            lines += [f'    {json.dumps(e)}' + (',' if i < len(v) - 1 else '') for i, e in enumerate(v)]
            lines.append(f'  ]{sep}')
        elif isinstance(v, dict):
            lines.append(f'  {json.dumps(key)}: {{')
            items = list(v.items())
            lines += [f'    {json.dumps(a)}: {json.dumps(b)}' + (',' if i < len(items) - 1 else '')
                      for i, (a, b) in enumerate(items)]
            lines.append(f'  }}{sep}')
        else:
            lines.append(f'  {json.dumps(key)}: {json.dumps(v)}{sep}')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def dumps_shared(sh):
    """shared.json: one line per role and per entry."""
    def block(b, pad):
        rows = [f'{pad}"roles": {{']
        rows += [f'{pad}  {json.dumps(k)}: {json.dumps(v)}' + (',' if i < len(b['roles']) - 1 else '')
                 for i, (k, v) in enumerate(b['roles'].items())]
        rows += [f'{pad}}},', f'{pad}"entries": [']
        rows += [f'{pad}  {json.dumps(e)}' + (',' if i < len(b['entries']) - 1 else '')
                 for i, e in enumerate(b['entries'])]
        return rows + [f'{pad}]']
    lines = ['{', f'  "note": {json.dumps(sh["note"])},', '  "hud": {'] + block(sh['hud'], '    ')
    lines += ['  },', '  "sprites": [']
    for i, sp in enumerate(sh['sprites']):
        lines += ['    {', f'      "palette": {sp["palette"]}, "name": {json.dumps(sp["name"])},',
                  f'      "pce": {json.dumps(sp["pce"])},'] + block(sp, '      ')
        lines.append('    }' + (',' if i < len(sh['sprites']) - 1 else ''))
    return '\n'.join(lines + ['  ]', '}']) + '\n'


def _store(entries, roles):
    for e, (code, out) in zip(entries, resolve(entries, roles)):
        e['nes'] = None if code is None else f'{code:02X}'
        e['out'] = f'{out:03X}'


def resolve_files(path=DATA):
    """Rewrite every file's `nes`/`out` from its roles."""
    path = Path(path)
    for p in sorted((path / 'stages').glob('*.json')):
        d = json.loads(p.read_text())
        _store(d['entries'], d['roles'])
        p.write_text(dumps(d))
    p = path / 'shared.json'
    sh = json.loads(p.read_text())
    _store(sh['hud']['entries'], sh['hud']['roles'])
    for sp in sh['sprites']:
        _store(sp['entries'], sp['roles'])
    p.write_text(dumps_shared(sh))


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'check'
    if cmd == 'resolve':
        resolve_files()
        print('resolved')
    elif cmd == 'check':
        problems = check(load())
        print('\n'.join(problems) or 'ok')
