"""Enhanced backdrop assets generated from the original ROM (native_gfx).

Every renderer shows eight horizontal pixel phases of tile pairs: a pair is
two cells that are neighbours in the backdrop loop, and its phase-p tile is
the 8 pixels starting p pixels into the left cell. This module builds the
loop from native columns (native_gfx.LOOPS), the pairs, and each renderer's
data format. Colours never change: a pair whose cells use different native
palettes is expressed in one palette that holds both cells' colours.
"""
from pathlib import Path

import native_gfx as N

REPO = Path(__file__).resolve().parents[1]


def loop_words(backdrop):
    override = {r: N.castle_sky for r in range(N.CASTLE_SKY_ROWS)} if backdrop.profile == 7 else None
    return backdrop.loop_words(row_override=override)


def build_pairs(backdrop, words, palette_of, palettes=None):
    """Pairs of neighbouring loop cells, first-seen order, one list per row.

    palette_of(row) -> target palette number of that row's pairs.
    palettes: {target palette: 16 colours} for patched palettes.
    Returns (pairs, rows): pairs[i] = (palette, left pixels, right pixels);
    rows[r][u] = pair index at loop position u; and per-row (first, end).
    """
    pairs, index, rows, ranges = [], {}, [], []
    for r, row in enumerate(words):
        target = palette_of(r)
        first = len(pairs)
        out = []
        for u in range(len(row)):
            a, b = backdrop.cell(row[u]), backdrop.cell(row[(u + 1) % len(row)])
            pal = palettes.get(target) if palettes else None
            key = (target, N.reindex(backdrop, a, target, pal), N.reindex(backdrop, b, target, pal))
            if key not in index:
                index[key] = len(pairs)
                pairs.append(key)
            out.append(index[key])
        rows.append(out)
        ranges.append((first, len(pairs)))
    return pairs, rows, ranges


def used_colours(backdrop, words):
    return {backdrop.colour(pal, v) for row in words for w in row
            for pal, px in [backdrop.cell(w)] for line in px for v in line if v}


def map_bytes(rows, slot_of, length=64):
    """Map rows of `length` entries: entry e shows the pair at loop position e mod L."""
    out = bytearray()
    for row in rows:
        out += bytes(slot_of(row[e % len(row)]) & 0xFF for e in range(length))
    return bytes(out)


def loop_include(length, extra=''):
    return (f'; Generated by scripts/native_backdrops.py.\n'
            f'LOOP_LENGTH = {length}\nLOOP_SPAN = {length * 8}\nMAP_WRAP = {64 % length}\n{extra}')


# Phase-atlas renderers: per phase one atlas of 32-byte pair tiles; 16-byte TIA
# copy routines per (phase within bank, row) upload a row's new pairs.
PHASE_ATLAS = {
    'stage11': {'profile': 0, 'bank': 0x40, 'per_bank': 3, 'tile': 0x280, 'map_org': 0x4800,
                'max_pairs': 83, 'map': 'smooth-map.bin', 'atlas': 'atlas-{}.bin',
                'inc': 'generated.inc', 'palette': 1},
    'stage31': {'profile': 2, 'bank': 0x47, 'per_bank': 2, 'tile': 0x80, 'map_org': 0x4600,
                # banks $48-$4B end at $7240: their tails hold 4-2 and castle data
                'max_pairs': 0x1240 // 64, 'map': 'p2-map.bin', 'atlas': 'p2-atlas-{}.bin',
                'inc': 'p2-generated.inc'},
    'stage32': {'profile': 4, 'bank': 0x4C, 'per_bank': 2, 'tile': 0x80, 'map_org': 0x4600,
                'max_pairs': 128, 'map': 'p4-map.bin', 'atlas': 'p4-atlas-{}.bin',
                'inc': 'p4-generated.inc'},
    'stage41': {'profile': 6, 'bank': 0x51, 'per_bank': 2, 'tile': 0x80, 'map_org': 0x4600,
                'max_pairs': 128, 'map': 'p6-map.bin', 'atlas': 'p6-atlas-{}.bin',
                'inc': 'p6-generated.inc'},
}


def phase_atlas(module, work, rom):
    cfg = PHASE_ATLAS[module]
    backdrop = N.Backdrop(rom, cfg['profile'])
    words = loop_words(backdrop)
    length, height = len(words[0]), backdrop.height
    palettes = None
    if 'palette' in cfg:
        # One patched palette (the native palette is scenery-only) holds the
        # backdrop's colours from both native palettes.
        merged = N.merged_palette(used_colours(backdrop, words), backdrop.name)
        palettes = {cfg['palette']: merged}
        (work / 'smooth-palette.bin').write_bytes(b''.join(c.to_bytes(2, 'little') for c in merged))
        palette_of = lambda r: cfg['palette']
    else:
        if any(w >> 12 for row in backdrop.rows for w in row):
            raise N.NativeError(f'{backdrop.name}: expected palette 0 only')
        palette_of = lambda r: 0
    pairs, rows, ranges = build_pairs(backdrop, words, palette_of, palettes)
    if len(pairs) > cfg['max_pairs']:
        raise N.NativeError(f'{backdrop.name}: {len(pairs)} pairs exceed {cfg["max_pairs"]} slots')
    size = len(pairs) * 32
    per = cfg['per_bank']
    for phase in range(8):
        (work / cfg['atlas'].format(phase)).write_bytes(b''.join(N.phase_images(a, b)[phase] for _, a, b in pairs))
    (work / cfg['map']).write_bytes(map_bytes(rows, lambda i: 0x80 + i))
    bank = cfg['bank']
    inc = [f'ATLAS_SIZE = {size}', 'phase_bank:', ' .db ' + ','.join(f'${bank + 1 + p // per:02x}' for p in range(8))]
    if per == 2:
        inc += ['phase_row_offset:', ' .db ' + ','.join(str((p % 2) * height * 2) for p in range(8))]
    inc.append('row_copy:')
    slots = [p % per for p in range(8)] if per == 3 else range(per)
    for slot in slots:
        inc.append(' .dw ' + ','.join(f'copy{slot}_{r}' for r in range(height)))
    if 'palette' in cfg:
        inc += ['extra_palette:', ' .incbin "smooth-palette.bin"']
    inc += [f' .org ${cfg["map_org"]:04x}', 'map_data:', f' .incbin "{cfg["map"]}"', ' .org $4c00']
    vram = cfg['tile'] * 16
    for slot in range(per):
        for r, (first, end) in enumerate(ranges):
            inc.append(f'copy{slot}_{r}:')
            if end > first:
                address = vram + first * 16
                inc += [' stz <$11', ' st0 #0', f' st1 #${address & 255:02x}', f' st2 #${address >> 8:02x}',
                        ' lda #2', ' sta <$11', ' st0 #2']
                inc += [f' tia ${0x6000 + slot * size + offset:04x},$0002,16' for offset in range(first * 32, end * 32, 16)]
            inc.append(' rts')
    inc.append('copy_end:')
    inc += [' .if (copy_end > $6000)', ' .fail', ' .endif']
    for phase in range(8):
        inc += [f' .bank ${bank + 1 + phase // per:02x}', f' .org ${0x6000 + (phase % per) * size:04x}',
                f' .incbin "{cfg["atlas"].format(phase)}"']
    (work / cfg['inc']).write_text('\n'.join(inc) + '\n')
    (work / 'loop.inc').write_text(loop_include(length))
    return {'pairs': len(pairs), 'length': length, 'seams': N.seams(backdrop, words)}


# Entry cameras of each round ($2E60 index) whose first frame shows backdrop;
# 0 also stands for rounds that open without backdrop on screen.
ROUND_CAMERAS = {3: [768, 768, 1792, 0], 7: [512, 0, 512, 0, 256, 0, 0, 0], 8: [0, 0, 1792, 0]}
STAGE61_CAMERAS = [2048]


def opening(length, cameras):
    """Per-round loop offsets so each round opens on the original's columns.

    Measured against the original's first frames (docs/validation): a round
    entered at camera 0 shows native column 0 at the left edge; one entered at
    camera C > 0 (a multiple of 16) shows native column 1 there, while the
    shared coordinate puts loop entry C/16 there (D = C/2 at entry).
    """
    return [0 if c == 0 else (1 - c // 16) % length for c in cameras]


# TIA renderers: per phase one atlas of pair tiles in data banks; a routine per
# (row, phase within bank) seeks VRAM and copies the row's new pairs with
# 32-byte TIA blocks, a NOP between blocks. The renderer still runs when the
# playfield split interrupt (raster line ~70) fires, and back-to-back blocks
# held that interrupt off for two blocks, over a line (5-2 and 6-3 showed the
# playfield one line low); see docs/pc-engine/LESSONS.md.
TIA = {
    'stage52': {'profile': 1, 'bank': 0x73, 'prefix': 'p1', 'data_banks': 4},
    'stage63': {'profile': 8, 'bank': 0x78, 'prefix': 'p8', 'data_banks': 2},
}


def seek_code(address):
    """stz <$11, st0 #0, st1/st2 address, lda #2, sta <$11, st0 #2"""
    return bytes([0x64, 0x11, 0x03, 0, 0x13, address & 255, 0x23, address >> 8, 0xa9, 2, 0x85, 0x11, 0x03, 2])


def tia(module, work, rom):
    cfg = TIA[module]
    backdrop = N.Backdrop(rom, cfg['profile'])
    if any(w >> 12 for row in backdrop.rows for w in row):
        raise N.NativeError(f'{backdrop.name}: expected palette 0 only')
    words = loop_words(backdrop)
    length, height = len(words[0]), backdrop.height
    pairs, rows, ranges = build_pairs(backdrop, words, lambda r: 0)
    if len(pairs) > 128:
        raise N.NativeError(f'{backdrop.name}: {len(pairs)} pairs exceed slots $80-$FF')
    size = len(pairs) * 32
    per = 8 // cfg['data_banks']
    if per * size > 0x2000:
        raise N.NativeError(f'{backdrop.name}: {per} phases of {size} bytes exceed a bank')
    prefix, bank = cfg['prefix'], cfg['bank']
    atlases = [b''.join(N.phase_images(a, b)[phase] for _, a, b in pairs) for phase in range(8)]
    for i in range(cfg['data_banks']):
        (work / f'{prefix}-code{i}.bin').write_bytes(b''.join(atlases[i * per:(i + 1) * per]))
    low = map_bytes(rows, lambda i: 0x80 + i)
    (work / f'{prefix}-map.bin').write_bytes(b''.join(low[r * 64:(r + 1) * 64] + bytes(64) for r in range(height)))
    code, routines = bytearray(), {}
    base = 0x5000 + 24 * height
    for r, (first, end) in enumerate(ranges):
        for slot in range(per):
            routines[r, slot] = base + len(code)
            if end > first:
                code += seek_code(0x0800 + first * 16)
                for i in range(first, end):
                    src = 0x6000 + slot * size + i * 32
                    if i > first:
                        code += b'\xea'
                    code += bytes([0xe3, src & 255, src >> 8, 0x02, 0x00, 0x20, 0x00])
            code += b'\x60'
    if base + len(code) > 0x6000:
        raise N.NativeError(f'{backdrop.name}: upload code ends at ${base + len(code):04x}')
    (work / f'{prefix}-tia-code.bin').write_bytes(bytes(code))
    inc = [' .org $4300', 'row_table:', ' .dw ' + ','.join(f'row{r}' for r in range(height))]
    if cfg['profile'] in ROUND_CAMERAS:
        inc += ['opening_fix:', ' .db ' + ','.join(map(str, opening(length, ROUND_CAMERAS[cfg['profile']])))]
    inc += [' .org $4400', f' .incbin "{prefix}-map.bin"', ' .org $5000']
    for r in range(height):
        inc += [f'row{r}:', ' .db ' + ','.join(str(bank + 1 + p // per) for p in range(8)),
                ' .db ' + ','.join(str(routines[r, p % per] & 255) for p in range(8)),
                ' .db ' + ','.join(str(routines[r, p % per] >> 8) for p in range(8))]
    inc += [f' .incbin "{prefix}-tia-code.bin"']
    # Unrolled column writes: column_entry_*[n] runs n columns (as REV5 does).
    inc += ['column_entry_lo:', ' .db ' + ','.join(f'LOW(column{33 - n})' for n in range(34)),
            'column_entry_hi:', ' .db ' + ','.join(f'HIGH(column{33 - n})' for n in range(34))]
    for c in range(33):
        inc += [f'column{c}:', ' ldx $0002', ' lda $0003', ' cmp #16', f' bcs foreground{c}', ' lda [<$06],y',
                ' tax', ' lda [<$0a],y', f'foreground{c}:', ' stx $0002', ' sta $0003', ' iny']
    inc += ['column33:', ' rts', 'renderer_end:', ' .if (renderer_end > $6000)', ' .fail', ' .endif']
    for i in range(cfg['data_banks']):
        inc += [f' .bank ${bank + 1 + i:02x}', ' .org $6000', f' .incbin "{prefix}-code{i}.bin"']
    (work / f'{prefix}-generated.inc').write_text('\n'.join(inc) + '\n')
    extra = f'FIXED_ANCHOR = {8 * length - 56}\n' if module == 'stage52' else ''
    (work / 'loop.inc').write_text(loop_include(length, extra))
    return {'pairs': len(pairs), 'length': length, 'seams': N.seams(backdrop, words)}


# REV5 renderers: immediate-store upload routines in code banks (rev5_texture).
# 2-2 rows 12-15 use patched palettes 13 and 14 (native rows 12-15 mix
# palettes 0 and 2; row 15 needs opaque black as well).
REV5 = {
    'stage22': {'profile': 3, 'prefix': 'p3', 'rowpal': [1] * 7 + [0] * 5 + [13] * 3 + [14],
                'merged': {13: range(12, 15), 14: range(15, 16)}},
    'stage42': {'profile': 5, 'prefix': 'p5', 'rowpal': [0] * 22},
}


def rev5(module, work, rom):
    import re
    import rev5_texture as R
    cfg = REV5[module]
    backdrop = N.Backdrop(rom, cfg['profile'])
    words = loop_words(backdrop)
    length = len(words[0])
    palettes = {target: N.merged_palette(used_colours(backdrop, [words[r] for r in rows]),
                                         f'{backdrop.name} palette {target}')
                for target, rows in cfg.get('merged', {}).items()}
    texture = [[N.reindex(backdrop, backdrop.cell(w), cfg['rowpal'][r], palettes.get(cfg['rowpal'][r]))
                for w in row] for r, row in enumerate(words)]
    out = R.generate(module, texture, cfg['rowpal'])
    R.write(module, work, out)
    # Code banks the generator leaves unused stay empty (the include may still
    # name them).
    for i in range(len(out['bins']), 16):
        (work / f'{cfg["prefix"]}-code{i}.bin').write_bytes(b'')
    inc_path = work / f'{cfg["prefix"]}-generated.inc'
    inc = inc_path.read_text()
    for target, pal in palettes.items():
        inc, count = re.subn(rf'^palette{target}:\n \.dw .*$', f'palette{target}:\n .dw ' + ','.join(map(str, pal)),
                             inc, flags=re.M)
        if count != 1:
            raise N.NativeError(f'palette{target} not found in {inc_path.name}')
    if 'uniform_rows:' in inc:
        # Rows whose 64 map words are all equal, last row first (the renderer
        # indexes by its row counter).
        rows = len(cfg['rowpal'])
        flags = [int(len(set(zip(out['map'][r * 128:r * 128 + 64], out['map'][r * 128 + 64:r * 128 + 128]))) == 1)
                 for r in range(rows)]
        inc, count = re.subn(r'^uniform_rows:\n \.db .*$', 'uniform_rows:\n .db ' + ','.join(map(str, flags[::-1])),
                             inc, flags=re.M)
        if count != 1:
            raise N.NativeError(f'uniform_rows not found in {inc_path.name}')
    inc_path.write_text(inc)
    cameras = ROUND_CAMERAS.get(cfg['profile'], [])
    extra = ''.join(f'OPENING_{i} = {v}\n' for i, v in enumerate(opening(length, cameras)))
    (work / 'loop.inc').write_text(loop_include(length, extra))
    return {'pairs': out['pairs'], 'length': length, 'seams': N.seams(backdrop, words)}


def castle(module, work, rom):
    import castle_horizon as C
    length = len(N.LOOPS[C.PROFILE])
    if module == 'stage61-sky':
        C.write_sky(work, 'map.bin', rom)
        return {'length': None}
    cameras = ROUND_CAMERAS[C.PROFILE] if module == 'castle' else STAGE61_CAMERAS + [0] * 6
    out = C.write(work, 'map.bin' if module == 'castle' else 'mountain-map.bin', rom, module == 'castle')
    extra = ''.join(f'OPENING_{i} = {v}\n' for i, v in enumerate(opening(length, cameras)))
    (work / 'loop.inc').write_text(loop_include(length, extra))
    return {'pairs': out['pairs'], 'new': out['new'], 'length': length}


def prepare(module, work, rom):
    """Regenerate a module's backdrop data in its build directory."""
    if module in PHASE_ATLAS:
        return phase_atlas(module, work, rom)
    if module in TIA:
        return tia(module, work, rom)
    if module in REV5:
        return rev5(module, work, rom)
    if module in ('castle', 'stage61-mountains', 'stage61-sky'):
        return castle(module, work, rom)
    raise N.NativeError(f'No native backdrop generator for {module}')
